"""## MAIN PREDICTION FUNCTION"""

def predict_demand(raw_input):
    """
    Predict hourly bike demand.

    Steps:
    1. Validate input
    2. Convert input to DataFrame
    3. Apply feature engineering
    4. Arrange features in correct order
    5. Generate model prediction
    6. Convert log prediction back to real scale
    7. Log the prediction
    """

    # --------------------------------------
    # STEP 1: Validate input
    # --------------------------------------
    validate_input(raw_input)

    # --------------------------------------
    # STEP 2: Convert dictionary to DataFrame
    # --------------------------------------
    df = pd.DataFrame([raw_input])

    # --------------------------------------
    # STEP 3: Apply feature engineering
    # --------------------------------------
    df = add_cyclic_features(df)

    # --------------------------------------
    # STEP 4: Arrange features correctly
    # --------------------------------------
    df = df[MODEL_COLUMNS]

    # --------------------------------------
    # STEP 5: Generate prediction
    # --------------------------------------
    log_prediction = model.predict(df)[0]

    # --------------------------------------
    # STEP 6: Convert log prediction
    # back to original scale
    # --------------------------------------
    real_prediction = np.expm1(log_prediction)

    # Make sure prediction is not negative
    real_prediction = max(0.0, real_prediction)

    # --------------------------------------
    # STEP 7: Operational logging
    # --------------------------------------
    logger.info(
        f"Input: {raw_input} | "
        f"Prediction: {real_prediction:.2f}"
    )

    return real_prediction


