"""## FEATURE ENGINEERING"""

def add_cyclic_features(df):
    """
    Add cyclic representations of hour and month.

    This must reproduce the same feature engineering
    used when the model was trained.
    """

    df = df.copy()

    # Cyclic encoding for hour
    df["sin_hr"] = np.sin(
        2 * np.pi * df["hr"] / 24.0
    )

    df["cos_hr"] = np.cos(
        2 * np.pi * df["hr"] / 24.0
    )

    # Cyclic encoding for month
    df["sin_mnth"] = np.sin(
        2 * np.pi * df["mnth"] / 12.0
    )

    df["cos_mnth"] = np.cos(
        2 * np.pi * df["mnth"] / 12.0
    )

    return df


