def validate_input(raw_input):
    """
    Validate required fields and basic value ranges.
    """

    # Check that input is a dictionary
    if not isinstance(raw_input, dict):
        raise TypeError("Input must be provided as a dictionary.")

    # Check for missing columns
    missing = [
        column
        for column in REQUIRED_COLUMNS
        if column not in raw_input
    ]

    if missing:
        raise ValueError(
            f"Missing required input fields: {missing}"
        )

    # Check hour
    if not 0 <= raw_input["hr"] <= 23:
        raise ValueError(
            "hr must be between 0 and 23."
        )

    # Check month
    if not 1 <= raw_input["mnth"] <= 12:
        raise ValueError(
            "mnth must be between 1 and 12."
        )

    # Check season
    if not 1 <= raw_input["season"] <= 4:
        raise ValueError(
            "season must be between 1 and 4."
        )

    # Check weekday
    if not 0 <= raw_input["weekday"] <= 6:
        raise ValueError(
            "weekday must be between 0 and 6."
        )

    # Binary columns
    binary_columns = [
        "yr",
        "holiday",
        "workingday"
    ]

    for column in binary_columns:
        if raw_input[column] not in [0, 1]:
            raise ValueError(
                f"{column} must be either 0 or 1."
            )

    # Weather situation
    if not 1 <= raw_input["weathersit"] <= 4:
        raise ValueError(
            "weathersit must be between 1 and 4."
        )

    # Normalized continuous features
    normalized_columns = [
        "temp",
        "atemp",
        "hum",
        "windspeed"
    ]

    for column in normalized_columns:
        value = raw_input[column]

        if not 0 <= value <= 1:
            raise ValueError(
                f"{column} must be between 0 and 1."
            )

    return True


